# Генерирует bootstrap-inline.wxi: immediate CA с embedded bootstrap-schedule-upgrade.ps1 (2.0.2 без scripts на диске).
param(
    [string]$Root = $PSScriptRoot
)

$ErrorActionPreference = "Stop"
$scriptPath = Join-Path $Root "bootstrap-schedule-upgrade.ps1"
$outPath = Join-Path $Root "bootstrap-inline.wxi"
if (-not (Test-Path -LiteralPath $scriptPath)) {
    throw "Missing $scriptPath"
}

$bytes = [IO.File]::ReadAllBytes($scriptPath)
$b64 = [Convert]::ToBase64String($bytes)

$psCommand =
    '$ErrorActionPreference=''Stop'';' +
    '$b64=''' + $b64 + ''';' +
    '$bytes=[Convert]::FromBase64String($b64);' +
    '$f=Join-Path $env:TEMP (''bad-bootstrap-{0}.ps1'' -f [guid]::NewGuid().ToString(''N''));' +
    '[IO.File]::WriteAllBytes($f,$bytes);' +
    '& $f ''[OriginalDatabase]'';' +
    '$ec=$LASTEXITCODE;' +
    'Remove-Item -LiteralPath $f -Force -ErrorAction SilentlyContinue;' +
    'exit $ec'

# MSI SetProperty Value: [Prop] подставляется; литеральные [Convert] → [[]Convert[]]; $ → $$ в wxs (WiX → $ в property).
function Escape-PsCommandForMsiSetProperty([string]$command) {
    $c = $command
    $c = $c -replace '\[Convert\]', '[[]Convert[]]'
    $c = $c -replace '\[IO\.File\]', '[[]IO.File[]]'
    $c = $c -replace '\[guid\]', '[[]guid[]]'
    # WiX/MSI: $$ в исходнике → один $ в сохранённой строке команды
    $c = $c -replace '\$', '$$$$'
    $c = $c -replace '&', '&amp;'
    $c = $c -replace '"', '&quot;'
    return $c
}

$commandBody = Escape-PsCommandForMsiSetProperty -command $psCommand
# Immediate WixQuietExec читает WixQuietExecCmdLine, не имя CustomAction (WIX 0x80070057 иначе).
$wxsValue = '&quot;[System64Folder]WindowsPowerShell\v1.0\powershell.exe&quot; -NoProfile -NonInteractive -ExecutionPolicy Bypass -Command &quot;' +
    $commandBody +
    '&quot;'

$wxi = @"
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by generate-bootstrap-inline.ps1 — do not edit by hand. -->
<Include xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <SetProperty Id="WixQuietExecCmdLine"
               Value="$wxsValue"
               Sequence="execute"
               Before="BootstrapScheduleAction" />

  <CustomAction Id="BootstrapScheduleAction"
                BinaryRef="Wix4UtilCA_`$(sys.BUILDARCHSHORT)"
                DllEntry="WixQuietExec"
                Execute="immediate"
                Return="check"
                Impersonate="no" />
</Include>
"@

[IO.File]::WriteAllText($outPath, $wxi, [Text.UTF8Encoding]::new($false))
Write-Host "Wrote $outPath ($($wxi.Length) chars)"
